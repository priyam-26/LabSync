    )

);


-- ============================================================
-- 9. ADMIN TABLE SECURITY
-- ============================================================

drop policy if exists
"Admins can view their own admin record"
on public.admins;


create policy
"Admins can view their own admin record"

on public.admins

for select

to authenticated

using (
    user_id = auth.uid()
);


-- ============================================================
-- 10. AUTOMATIC DELETION OF FIXED COMPLAINTS
--
-- Fixed complaints older than 7 days are removed.
-- ============================================================


-- Enable pg_cron if available.

create extension if not exists pg_cron;


-- Remove an existing job with this name if present.

select cron.unschedule(
    jobid
)
from cron.job
where jobname =
      'delete-old-fixed-complaints';


-- Create the automatic cleanup job.

select cron.schedule(
    'delete-old-fixed-complaints',

    '0 0 * * *',

    $$
        delete from public.complaints

        where status = 'FIXED'

        and fixed_at is not null

        and fixed_at <=
            now() - interval '7 days';
    $$
);